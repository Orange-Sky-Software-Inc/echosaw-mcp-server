import { getResults } from '../echosaw-client.js';
import { buildResponse, McpToolResponse, AnalysisResultsData } from '../types.js';

export const getResultsToolDefinition = {
  name: 'echosaw_get_analysis_results',
  description: 'Retrieve structured analysis results generated by Echosaw for a completed job, including summaries, transcripts, detected entities, events, and other intelligence outputs.',
  inputSchema: {
    type: 'object' as const,
    properties: {
      mediaId: {
        type: 'string',
        description: 'The mediaId of a completed analysis',
      },
      section: {
        type: 'string',
        description: 'Optional: request a specific section of the results to reduce response size. One of: summary, transcript, safety, insights, metadata, downloads, all. Defaults to "all" with transcript truncated to 5000 characters. Use "transcript" to get the full transcript.',
        enum: ['summary', 'transcript', 'safety', 'insights', 'metadata', 'downloads', 'all'],
      },
    },
    required: ['mediaId'],
  },
  annotations: {
    title: 'Get Analysis Results',
    readOnlyHint: true,
    destructiveHint: false,
    idempotentHint: true,
    openWorldHint: true,
  },
};

export async function handleGetResults(args: { mediaId: string; section?: string }): Promise<McpToolResponse<AnalysisResultsData>> {
  const { mediaId, section } = args;
  const results = await getResults(mediaId) as Record<string, unknown>;

  // If a specific section is requested (not 'all'), extract just that section
  if (section && section !== 'all') {
    const sectionData = results[section] ?? null;
    return buildResponse('echosaw_get_analysis_results', { mediaId, report: { [section]: sectionData } }, {
      message: `Analysis results retrieved (section: ${section}).`,
    });
  }

  // For 'all' or omitted: return full response but truncate transcript.text to 5000 chars
  const report = results as Record<string, unknown>;
  const transcript = report['transcript'] as Record<string, unknown> | undefined;
  if (transcript && typeof transcript['text'] === 'string') {
    const text = transcript['text'] as string;
    if (text.length > 5000) {
      transcript['text'] = text.substring(0, 5000) + '... [truncated — use section: \'transcript\' for full text]';
    }
  }

  // Warn if response is very large
  const responseJson = JSON.stringify(results);
  if (responseJson.length > 80000) {
    console.warn(`[echosaw_get_analysis_results] Response size ${responseJson.length} chars (~${Math.round(responseJson.length / 4)} tokens) exceeds recommended limit. Consider using the section parameter.`);
  }

  return buildResponse('echosaw_get_analysis_results', { mediaId, report: results }, {
    message: 'Analysis results retrieved.',
  });
}
